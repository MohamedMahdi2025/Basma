  hr('5002', { managerId: ids['5001'], hireDate: '2020-01-01', nationality: 'EG', contractType: 'fixed', contractEnd: '2028-12-31', departmentId: dept.id });
  hr('5003', { managerId: ids['5001'], hireDate: '2022-02-01', nationality: 'SA', departmentId: dept.id });
  hr('5004', { managerId: ids['5001'], hireDate: '2021-05-01', nationality: 'IN', contractType: 'fixed', contractEnd: '2028-12-31' });
